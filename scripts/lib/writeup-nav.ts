/**
 * Generated footer for each tools/*.md writeup: a breadcrumb back to the
 * index and links to other writeups in the same category.
 *
 * Why: search engines send readers straight to individual writeups, and
 * most of them had no way back to the list. The block sits between
 * markers, so rebuilding replaces it and never touches the hand-written text.
 */
import type { Category, Tool } from './data.ts';

export const NAV_START = '<!-- megalist:nav - generated by `npm run build`, do not edit -->';
export const NAV_END = '<!-- /megalist:nav -->';
const MAX_RELATED = 6;

/** GitHub's heading anchor: lowercase, drop punctuation, spaces to hyphens. */
export function githubSlug(heading: string): string {
  return heading.toLowerCase().replace(/[^\p{L}\p{N} _-]/gu, '').replace(/ /g, '-');
}

export function navBlock(tool: Tool, tools: Tool[], categories: Category[]): string {
  const cat = categories.find((c) => c.id === tool.category)!;
  const related = tools
    .filter((t) => t !== tool && t.category === tool.category && t.writeup)
    .sort((a, b) => Number(b.tier === 'top') - Number(a.tier === 'top') || (a.order ?? Infinity) - (b.order ?? Infinity))
    .slice(0, MAX_RELATED)
    .map((t) => `[${t.name}](${t.writeup!.replace(/^tools\//, '')})`);
  const lines = [
    NAV_START,
    '',
    '---',
    '',
    `**[AI Megalist](../README.md)** › [${cat.title}](../README.md#${githubSlug(cat.title)})`,
  ];
  if (related.length) lines.push('', `More in ${cat.title}: ${related.join(' · ')}`);
  lines.push(NAV_END);
  return lines.join('\n');
}

/** Replace (or append) the generated block in a writeup's Markdown. */
export function withNav(markdown: string, block: string): string {
  const start = markdown.indexOf(NAV_START);
  const base = start === -1 ? markdown.trimEnd() : markdown.slice(0, start).trimEnd();
  return `${base}\n\n${block}\n`;
}
