/**
 * List tools whose last_verified is older than N days (default 90).
 *
 *   node scripts/stale.ts [--days 90] [--out report.md]
 *
 * Writes an empty file when nothing is stale, so upsert-issue.ts can close
 * the tracking issue.
 */
import { writeFileSync } from 'node:fs';
import { parseArgs } from 'node:util';
import { loadData } from './lib/data.ts';

const { values } = parseArgs({ options: { days: { type: 'string', default: '90' }, out: { type: 'string' } } });
const days = Number(values.days);
const cutoff = new Date(Date.now() - days * 86_400_000).toISOString().slice(0, 10);
const stale = loadData().tools.filter((t) => t.last_verified < cutoff).sort((a, b) => a.last_verified.localeCompare(b.last_verified));

const report = stale.length
  ? `${stale.length} tool(s) were last verified more than ${days} days ago (before ${cutoff}).

Check each one still works, still matches its category and best_for line, then
set \`last_verified\` to today in \`data/tools.yaml\` and run \`npm run build\`.

| Tool | Category | Last verified | Link |
| :-- | :-- | :-- | :-- |
${stale.map((t) => `| ${t.name} | ${t.category} | ${t.last_verified} | ${t.url} |`).join('\n')}

<sub>Generated by scripts/stale.ts. This issue is updated in place each month.</sub>\n`
  : '';

if (values.out) writeFileSync(values.out, report);
else console.log(report || `Nothing older than ${days} days.`);
