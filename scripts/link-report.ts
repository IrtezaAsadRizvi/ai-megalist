/**
 * Turn lychee's JSON output into a Markdown report grouped by tool.
 *
 *   node scripts/link-report.ts lychee.json report.md
 *
 * Writes an empty report when every link passed.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { loadData } from './lib/data.ts';

type Failure = { url: string; status?: { text?: string; code?: number; details?: string } | string };
const [input, output] = process.argv.slice(2);
const json = JSON.parse(readFileSync(input, 'utf8'));
// lychee has used both names for the failure map across versions
const maps: Record<string, Failure[]>[] = [json.fail_map, json.error_map, json.timeout_map].filter(Boolean);
const failures = new Map<string, string>(); // url -> status text
for (const m of maps) for (const list of Object.values(m)) for (const f of list) {
  const s = typeof f.status === 'string' ? f.status : [f.status?.code, f.status?.text, f.status?.details].filter(Boolean).join(' ');
  failures.set(f.url, s || 'failed');
}

const { tools } = loadData();
const strip = (u: string) => u.replace(/^file:\/\/.*?\/(tools\/)/, '$1').replace(/\/+$/, '');
const rows = [...failures].map(([url, status]) => {
  const t = tools.find((x) => strip(x.url) === strip(url) || (x.writeup && strip(url).endsWith(x.writeup)));
  return `| ${t?.name ?? '(not a tool row)'} | ${url} | ${status.replace(/\|/g, '/')} |`;
}).sort();

const report = rows.length
  ? `The weekly link check found ${rows.length} failing link(s).

For each tool: confirm the site is really gone (some sites block bots), then
either fix \`url\` in \`data/tools.yaml\` or open a PR proposing removal.

| Tool | Link | Status |
| :-- | :-- | :-- |
${rows.join('\n')}

<sub>Generated by .github/workflows/links.yml. This issue is updated in place on each run.</sub>\n`
  : '';
writeFileSync(output, report);
console.log(rows.length ? `${rows.length} failing link(s)` : 'All links OK');
